#!/usr/bin/env python3
"""Generate the Ansible inventory from the Terraform state.

Reads the `all_nodes` output (hostname -> IP) produced by `terraform apply`
and writes ansible/inventory/generated.ini with the [master] and [workers]
groups used by site.yml, k8s.yml and verify.yml.

Environment overrides:
  ADMIN_USER  admin user created by cloud-init (default: ubuntu)
  SSH_KEY     private key path used by Ansible (default: ~/.ssh/id_ed25519)
"""

import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TF_DIR = os.path.join(ROOT, "terraform")
INVENTORY = os.path.join(ROOT, "ansible", "inventory", "generated.ini")

ADMIN_USER = os.environ.get("ADMIN_USER", "ubuntu")
SSH_KEY = os.environ.get("SSH_KEY", "~/.ssh/id_ed25519")


def fetch_nodes():
    try:
        proc = subprocess.run(
            ["terraform", "-chdir", TF_DIR, "output", "-json", "all_nodes"],
            capture_output=True,
            text=True,
        )
    except FileNotFoundError:
        sys.exit("terraform binary not found - install Terraform first")

    if proc.returncode != 0:
        sys.exit(
            "`terraform output all_nodes` failed (has `make cluster` been run yet?)\n"
            + proc.stderr.strip()
        )

    return json.loads(proc.stdout)["all_nodes"]["value"]


def main():
    nodes = fetch_nodes()
    if not nodes:
        sys.exit("Terraform output `all_nodes` is empty - nothing to inventory")

    masters = sorted(n for n in nodes if n.startswith("master-"))
    workers = sorted(n for n in nodes if n.startswith("worker-"))
    unknown = sorted(set(nodes) - set(masters) - set(workers))
    if unknown:
        sys.exit(f"Unrecognized node names (expected master-*/worker-*): {unknown}")

    lines = [
        "# Generated by scripts/generate-inventory.py - do not edit by hand.",
        "",
        "[master]",
        *[f"{name} ansible_host={nodes[name]}" for name in masters],
        "",
        "[workers]",
        *[f"{name} ansible_host={nodes[name]}" for name in workers],
        "",
        "[all:vars]",
        f"ansible_user={ADMIN_USER}",
        f"ansible_ssh_private_key_file={SSH_KEY}",
    ]

    with open(INVENTORY, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"Wrote {INVENTORY}: {len(masters)} master(s), {len(workers)} worker(s)")


if __name__ == "__main__":
    main()
